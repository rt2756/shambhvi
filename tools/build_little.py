import json, os, sys

OUT = os.path.join(sys.argv[1] if len(sys.argv) > 1 else ".", "content", "little")
os.makedirs(OUT, exist_ok=True)

def Q(t, o, h, p=None, k=None, c=None, x=False):
    q = {"t": t}
    if p: q["p"] = p
    q["o"] = o
    q["h"] = h
    if k: q["k"] = k
    if c: q["c"] = c
    if x: q["x"] = True
    return q

def rows(em, n, per=5):
    """n copies of an emoji, in rows of 5 so it can be counted (and seen) in fives."""
    full, rest = divmod(n, per)
    lines = [em * per] * full + ([em * rest] if rest else [])
    return "\n".join(lines)

def count(em, n, name):
    opts = [n, n + 1, n - 1 if n > 1 else n + 2, n + 2 if n > 1 else n + 3]
    h = "Touch each one and say one number: 1, 2, 3 … The last number you say is how many." if n <= 10 else \
        "Each full row has 5. Count the rows in fives (5, 10, 15 …), then count on the rest one by one."
    return Q(f"How many {name}?", [str(v) for v in opts], h, p=rows(em, n), c=em)

def nums(right, *wrong):
    return [str(right)] + [str(w) for w in wrong]

T = []   # (slug, data)

def topic(slug, title, emoji, group, parent, ask, r1, r2, r3):
    T.append((slug, {"title": title, "emoji": emoji, "group": group,
                     "parent": [{"learn": l, "why": w} for l, w in parent],
                     "ask": ask, "rounds": [r1, r2, r3]}))

