def add(a, b, w, story=None, em=None, h=None):
    t = story or f"{a} + {b} = ?"
    p = (em * a + " ➕ " + em * b) if em else None
    return Q(t, nums(a + b, *w), h or f"Start at {max(a,b)} and count on {min(a,b)} more.", p=p, k=f"{a}+{b}")

