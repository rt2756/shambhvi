def tri_cells(f, x0, y0, cells, s, fill):
    """Triangular grid cells (i, j, up): up triangles have vertices (i,j),(i+1,j),(i,j+1) in lattice coords."""
    def L(i, j): return P(x0 + (i + j / 2) * s, y0 + j * C30 * s)
    for i, j, up in cells:
        pts = [L(i, j), L(i + 1, j), L(i, j + 1)] if up else [L(i + 1, j), L(i + 1, j + 1), L(i, j + 1)]
        f.poly(pts, fill=fill)

