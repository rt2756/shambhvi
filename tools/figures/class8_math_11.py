def gasket(n):
    tris = [((0.0, 0.0), (1.0, 0.0), (0.5, C30))]
    for _ in range(n):
        new = []
        for a, b, c in tris:
            ab, bc, ca = mul(add(a, b), .5), mul(add(b, c), .5), mul(add(c, a), .5)
            new += [(a, ab, ca), (ab, b, bc), (ca, bc, c)]
        tris = new
    return tris

