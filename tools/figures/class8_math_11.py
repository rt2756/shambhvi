# ================================================================ cube nets
DIRS = {"E": (1, 0), "W": (-1, 0), "N": (0, 1), "S": (0, -1)}

def roll(o, d):
    b, t, n, s, e, w = o["B"], o["T"], o["N"], o["S"], o["E"], o["W"]
    if d == "E": return dict(B=e, E=t, T=w, W=b, N=n, S=s)
    if d == "W": return dict(B=w, W=t, T=e, E=b, N=n, S=s)
    if d == "N": return dict(B=n, N=t, T=s, S=b, E=e, W=w)
    return dict(B=s, S=t, T=n, N=b, E=e, W=w)

def is_cube_net(cells):
    cells = set(cells)
    start = min(cells)
    seen = {start: dict(B=0, T=1, N=2, S=3, E=4, W=5)}
    stack = [start]
    while stack:
        c = stack.pop()
        for d, (dx, dy) in DIRS.items():
            nb = (c[0] + dx, c[1] + dy)
            if nb in cells and nb not in seen:
                seen[nb] = roll(seen[c], d); stack.append(nb)
    return len(seen) == 6 and len({o["B"] for o in seen.values()}) == 6

def norm(cells):
    mx = min(x for x, y in cells); my = min(y for x, y in cells)
    return tuple(sorted((x - mx, y - my) for x, y in cells))

def canon(cells):
    forms = []
    pts = list(cells)
    for _ in range(4):
        pts = [(y, -x) for x, y in pts]
        forms.append(norm(pts)); forms.append(norm([(-x, y) for x, y in pts]))
    return min(forms)

def free_polyominoes(n):
    shapes = {canon([(0, 0)])}
    for _ in range(n - 1):
        new = set()
        for s in shapes:
            for x, y in s:
                for dx, dy in DIRS.values():
                    c = (x + dx, y + dy)
                    if c not in s:
                        new.add(canon(list(s) + [c]))
        shapes = new
    return sorted(shapes)

