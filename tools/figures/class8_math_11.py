def koch(n):
    pts = [(0.0, 0.0), (0.5, C30), (1.0, 0.0)]
    pts = [pts[0], pts[1], pts[2]]
    segs = [(pts[0], pts[1]), (pts[1], pts[2]), (pts[2], pts[0])]
    for _ in range(n):
        new = []
        for a, b in segs:
            d = ((b[0] - a[0]) / 3, (b[1] - a[1]) / 3)
            p1 = (a[0] + d[0], a[1] + d[1]); p2 = (a[0] + 2 * d[0], a[1] + 2 * d[1])
            # bump outward: rotate d by +60° (the triangle is traced clockwise)
            ang = math.radians(60)
            r = (d[0] * math.cos(ang) - d[1] * math.sin(ang), d[0] * math.sin(ang) + d[1] * math.cos(ang))
            peak = (p1[0] + r[0], p1[1] + r[1])
            new += [(a, p1), (p1, peak), (peak, p2), (p2, b)]
        segs = new
    return segs

