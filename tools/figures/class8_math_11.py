# ================================================================ fractals
def carpet(n):
    """Squares (x, y, size) remaining after n steps, starting from the unit square scaled to 1."""
    sq = [(0.0, 0.0, 1.0)]
    for _ in range(n):
        new = []
        for x, y, s in sq:
            t = s / 3
            new += [(x + i * t, y + j * t, t) for i in range(3) for j in range(3) if (i, j) != (1, 1)]
        sq = new
    return sq

