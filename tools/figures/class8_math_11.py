# ---------------------------------------------------------------- cuboid nets drawn to scale
def cuboid_net(f, x0, y0, L, B, H, k):
    """Net of an L x B x H cuboid: a column of four faces, each L wide (top B, front H, bottom B,
    back H, from the top down), with the two end faces (B wide, H tall) beside the front face."""
    y = y0
    tops = {}
    for h, name in [(B, "top"), (H, "front"), (B, "bottom"), (H, "back")]:
        y -= h * k
        rect(f, x0, y, L * k, h * k, fill=BLUE)
        f.text(P(x0 + L * k / 2, y + h * k / 2 - 6), f"{L} × {h}", size=11)
        tops[name] = y
    yf = tops["front"]
    for xx in (x0 - B * k, x0 + L * k):
        rect(f, xx, yf, B * k, H * k, fill=ORANGE)
        f.text(P(xx + B * k / 2, yf + H * k / 2 - 6), f"{B}×{H}", size=10)
    return 2 * (L * B + L * H + B * H)

