@fig
def penrose():
    f = Fig("penrose")
    n = 4
    cubes = [(i, 0, 0) for i in range(n)] + [(n, 0, k) for k in range(n)] + [(n, -j, n) for j in range(n)]
    # drawing order: the usual back-to-front order, except the first cubes go on top at the end,
    # which is the trick that makes the impossible loop look closed
    seq = sorted(cubes, key=lambda c: (c[0] - c[1] + c[2], c[2]))
    seq = [c for c in seq if c not in cubes[:2]] + cubes[:2]
    draw_iso(f, cubes, u=20, order=seq)
    p_end, p_start = iso(n, -n, n), iso(0, 0, 0)
    assert abs(p_end[0] - p_start[0]) < 1e-9 and abs(p_end[1] - p_start[1]) < 1e-9   # the loop "closes" on paper
    return f

