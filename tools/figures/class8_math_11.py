# ================================================================ cubes: isometric drawing and views
def iso(x, y, z, u=18):
    return P((x + y) * C30 * u, (z + (y - x) / 2) * u)

def draw_iso(f, cubes, x0=0, y0=0, u=18, order=None):
    cubes = list(cubes)
    seq = order or sorted(cubes, key=lambda c: (c[0] - c[1] + c[2], c[2]))
    S = set(cubes)
    def Q(x, y, z): q = iso(x, y, z, u); return P(q[0] + x0, q[1] + y0)
    for (x, y, z) in seq:
        if (x, y, z + 1) not in S or order:
            f.poly([Q(x, y, z + 1), Q(x + 1, y, z + 1), Q(x + 1, y + 1, z + 1), Q(x, y + 1, z + 1)], fill=TOP)
        if (x, y - 1, z) not in S or order:
            f.poly([Q(x, y, z), Q(x + 1, y, z), Q(x + 1, y, z + 1), Q(x, y, z + 1)], fill=FRONT)
        if (x + 1, y, z) not in S or order:
            f.poly([Q(x + 1, y, z), Q(x + 1, y + 1, z), Q(x + 1, y + 1, z + 1), Q(x + 1, y, z + 1)], fill=RIGHT)

def views(cubes):
    front = {(x, z) for x, y, z in cubes}
    top = {(x, y) for x, y, z in cubes}
    side = {(y, z) for x, y, z in cubes}          # seen from the right: front (y = 0) on the left
    return front, top, side

def draw_view(f, x0, y0, cells, u=14, fill="#ffffff"):
    for a, b in cells:
        rect(f, x0 + a * u, y0 + b * u, u, u, fill=fill)

def view_panel(f, x0, y0, cubes, u=14, label=True):
    fr, tp, sd = views(cubes)
    xs = x0
    for name, cells in [("front", fr), ("top", tp), ("side", sd)]:
        draw_view(f, xs, y0, cells, u)
        if label: f.label(P(xs + 1.5 * u, y0 - 16), name, size=11, color=GIVEN)
        xs += (max(a for a, b in cells) + 2) * u + 14

